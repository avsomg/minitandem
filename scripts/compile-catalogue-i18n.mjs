// German and French card texts for the app. Reads the checked translations of the private translation pipeline, one JSON per card
// (<folder>/de/<id>.json, <folder>/fr/<id>.json), and writes data-de.js and data-fr.js: per card only the digest of the English strings
// the translation was made from (rev) and the translated strings by field path. Check records, model names, notes and reasons stay private.
// The folder: the first argument, else MINITANDEM_TRANSLATIONS, else the path in the local, git-ignored file .translations-path.
// Usage: node scripts/compile-catalogue-i18n.mjs [folder]
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';

export const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
export const LANGS=['de','fr'];
export function translationsFolder(argument=''){
  const local=path.join(root,'.translations-path');
  const folder=argument||process.env.MINITANDEM_TRANSLATIONS||(fs.existsSync(local)?fs.readFileSync(local,'utf8').trim():'');
  return folder&&LANGS.every(lang=>fs.existsSync(path.join(folder,lang)))?folder:'';
}
// The English cards as the page assembles them, the unit builder and the order of the practical facts.
export function english(){
  const context={window:{},structuredClone,URL,TextEncoder};
  for(const file of ['data.js','data-reviewed.js','data-practical.js','regions.js','data-geo.js','catalogue-i18n.js','views.js'])vm.runInNewContext(fs.readFileSync(path.join(root,file),'utf8'),context,{filename:file});
  return {cards:context.window.ACTIVITIES,CI:context.window.MinitandemCatalogueI18n,order:context.window.MinitandemViews.PRACTICAL_ORDER};
}
// One language: {data: {id: {rev, strings}}, report}. A file that does not belong to a current card, or a string that is not text,
// is left out and named in the report; nothing else of the private record is read.
export function compile(folder,lang,{cards,CI,order}=english()){
  const ids=new Set(cards.map(card=>card.id)),data={},report={files:0,cards:0,strings:0,unknownCards:[],unmapped:[],untranslated:[],stale:[],invalid:[]};
  for(const name of fs.readdirSync(path.join(folder,lang)).filter(name=>name.endsWith('.json')&&name!=='summary.json').sort()){
    report.files++;
    const record=JSON.parse(fs.readFileSync(path.join(folder,lang,name),'utf8')),id=name.slice(0,-5);
    const translations=record?.result?.translations;
    if(record?.id!==id||record?.lang!==lang||!/^[0-9a-f]{64}$/.test(record?.revision||'')||!translations||typeof translations!=='object'){report.invalid.push(id);continue;}
    if(!ids.has(id)){report.unknownCards.push(id);continue;}
    const card=cards.find(a=>a.id===id),source=record.unit?.strings||{},strings={};
    for(const [key,text] of Object.entries(translations)){
      if(typeof text!=='string'||!text.trim()||/[\u0400-\u04FF]/.test(text)||!Object.hasOwn(source,key)){report.unmapped.push(`${id} ${key}`);continue;}
      strings[key]=text;
    }
    for(const key of Object.keys(source))if(!Object.hasOwn(strings,key))report.untranslated.push(`${id} ${key}`);
    if(CI.revision(card,order)!==record.revision)report.stale.push(id);
    data[id]={rev:record.revision,strings};report.cards++;report.strings+=Object.keys(strings).length;
  }
  return {data,report};
}
const NAMES={de:'German',fr:'French'};
export function code(lang,data){
  return `/* Generated by scripts/compile-catalogue-i18n.mjs from the checked ${NAMES[lang]} translations of the cards. Per card: rev, the digest of the
   English strings the translation was made from, and the translated strings by field path (catalogue-i18n.js). A card whose English has
   changed since is shown in English. Loaded only when the interface is ${NAMES[lang]}. */
(window.MINITANDEM_CARDS = window.MINITANDEM_CARDS || {}).${lang} = {
${Object.entries(data).map(([id,entry])=>JSON.stringify(id)+':'+JSON.stringify(entry)).join(',\n')}
};
`;
}
if(process.argv[1]&&path.resolve(process.argv[1])===fileURLToPath(import.meta.url)){
  const folder=translationsFolder(process.argv[2]);
  if(!folder)throw Error('No translation folder: pass it as the first argument, set MINITANDEM_TRANSLATIONS or write it to .translations-path');
  const source=english(),summary={};
  for(const lang of LANGS){
    const {data,report}=compile(folder,lang,source);
    if(report.invalid.length)throw Error(`${lang}: unreadable translation records: ${report.invalid.join(', ')}`);
    const file=`data-${lang}.js`,text=code(lang,data);
    fs.writeFileSync(path.join(root,file),text);
    summary[lang]={file,bytes:Buffer.byteLength(text),cards:report.cards,ofCatalogue:source.cards.length,strings:report.strings,stale:report.stale,
      missingCards:source.cards.map(card=>card.id).filter(id=>!data[id]),unknownCards:report.unknownCards,unmapped:report.unmapped,untranslated:report.untranslated};
  }
  console.log(JSON.stringify(summary,null,2));
}
