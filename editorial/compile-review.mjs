import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {loadCatalog} from './quality.mjs';
import {digest} from './jobs.mjs';
import {validateDraft,validateFullReview,applyDraftRecord} from './workflow.mjs';
import {fullReviewFields} from './field-contract.mjs';
import {publicApprovedUpdates} from './catalogue-journal.mjs';
import {PROJECT_ID} from './project-id.mjs';

// The English base in data.js already holds everything the old deep-review receipts and the old update journal contributed
// (migration/rebase-manifest.json lists them per card). This compiles only the journal of approvals made on top of that base.
const here=path.dirname(fileURLToPath(import.meta.url));
const root=path.dirname(here);
const updatesFile=path.join(here,'approved-updates.json');
const updates=fs.existsSync(updatesFile)?JSON.parse(fs.readFileSync(updatesFile,'utf8')):{schema:1,project:PROJECT_ID,updates:[]};
assert.equal(updates.schema,1);assert.equal(updates.project,PROJECT_ID);assert.ok(Array.isArray(updates.updates));
const currentById=new Map(loadCatalog().ACTIVITIES.map(a=>[a.id,a]));
for(const update of updates.updates){
  assert.match(update.approvalArtifact,/^[a-f0-9]{64}$/);
  const artifact=JSON.parse(fs.readFileSync(path.join(here,'agent-artifacts',update.approvalArtifact+'.json'),'utf8'));
  assert.equal(digest(artifact),update.approvalArtifact);assert.equal(artifact.project,PROJECT_ID);assert.equal(artifact.role,'verify');
  assert.equal(artifact.jobId,update.jobId);assert.equal(artifact.result.verdict,'approve');
  assert.equal(artifact.result.draftHash,digest(update.draft));
  assert.equal(digest(update.baseRecord),update.cardRevision,'Approved base revision mismatch');
  assert.match(update.appliedRecordRevision,/^[a-f0-9]{64}$/);
  const frozen=JSON.parse(fs.readFileSync(path.join(here,'correction-versions',update.appliedRecordRevision+'.json'),'utf8'));
  assert.equal(digest(frozen),update.appliedRecordRevision);
  assert.deepEqual(frozen.research,update.research);
  assert.ok(currentById.has(update.draft.cardId),'Unknown approved card');
  validateDraft(update.draft,update.baseRecord,{historical:true});
  if(update.draft.reviewCoverage){
    validateFullReview(update.draft,update.baseRecord,{date:update.approvedOn});
    assert.ok(fullReviewFields(update.baseRecord).every(field=>artifact.result.checkedCoverage?.includes(field)),'Full review lacks independent coverage approval');
    assert.ok(artifact.result.approvedBindings?.includes('review.coverage'),'Full review lacks coverage binding approval');
  }
  assert.equal(digest(applyDraftRecord(update.baseRecord,update.draft,update.approvedOn)),update.appliedRecordRevision,'Applied snapshot differs from approved patch');
}
const approved=publicApprovedUpdates(updates);
const runtime=`/* Generated by editorial/compile-review.mjs from editorial/approved-updates.json. Approve changes through the controller, not in this file. */
(() => {
  window.APPROVED_UPDATES = ${JSON.stringify(approved,null,2)};
})();
`;
fs.writeFileSync(path.join(root,'data-reviewed.js'),runtime);
console.log(JSON.stringify({journalUpdates:updates.updates.length,applied:approved.length,superseded:updates.updates.length-approved.length},null,2));
